-- Tests resolving the theme of the site configuration.

-- ============================================================================
-- SETUP
-- ============================================================================

begin;
select plan(1);

-- ============================================================================
-- VARIABLES
-- ============================================================================

\set siteID '0c200000-0000-0000-0000-000000000001'

-- ============================================================================
-- SEED DATA
-- ============================================================================

-- Site configuration whose theme is resolved
insert into site (site_id, description, theme, title)
values (
    :'siteID',
    'Site description',
    '{"primary_color": "#0c2001"}'::jsonb,
    'Site'
);

-- ============================================================================
-- TESTS
-- ============================================================================

-- Should return the theme of the site configuration
select is(
    site_theme(),
    '{"primary_color": "#0c2001"}'::jsonb,
    'Should return the theme of the site configuration'
);

-- ============================================================================
-- CLEANUP
-- ============================================================================

select * from finish();
rollback;
